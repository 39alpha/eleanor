import json
from enum import StrEnum
from pathlib import Path
from typing import TextIO

import click
import yaml

from eleanor.order import Order
from eleanor.output.postgres.persistence.converters import normalize_dict
from eleanor.typing import StrPath

_PROPERTIES: tuple[str, ...] = (
    "name",
    "creator",
    "create_date",
    "tags",
    "notes",
    "eleanor_version",
    "seed",
    "kernel",
    "navigator",
    "water_mass",
    "temperature",
    "pressure",
    "elements",
    "species",
    "reactants",
    "suppressions",
    "constraints",
)


_OPTIONAL_PROPERTIES: frozenset[str] = frozenset(
    {
        "tags",
        "notes",
        "species",
        "reactants",
        "suppressions",
        "constraints",
    }
)


class DumpFormat(StrEnum):
    YAML = "yaml"
    JSON = "json"


_DUMP_FORMATS: frozenset[DumpFormat] = frozenset([DumpFormat.YAML, DumpFormat.JSON])


def _is_empty_value(value: object) -> bool:
    """Determine if a property counts as "empty" for the purposes of output."""
    return value is None or (isinstance(value, (str, dict, list, set)) and len(value) == 0)


def _prepare_order(order: Order | dict[str, object], keep_empty: bool = False) -> dict[str, object]:
    """Prepare and order for output.

    This amounts to canonically reordering and dropping or keeping empty
    optional properties per the `keep_empty` argument.
    """
    if isinstance(order, Order):
        order = normalize_dict(order, "order")

    try:
        return {
            prop: order[prop]
            for prop in _PROPERTIES
            if (keep_empty and prop in _OPTIONAL_PROPERTIES) or not _is_empty_value(order[prop])
        }
    except KeyError as e:
        msg = f"order is missing the {e.args[0]!r} property; it was likely generated by older version of Eleanor"
        raise click.ClickException(msg) from e


def dump_order(
    output: StrPath | TextIO,
    order: Order | dict[str, object],
    format: DumpFormat | None = None,
    keep_empty: bool = True,
) -> None:
    """Dump an order suitable for rerunning Eleanor."""
    if isinstance(output, (str, Path)):
        with Path(output).open("w") as fp:
            dump_order(fp, order, format, keep_empty)
        return

    order_raw = _prepare_order(order, keep_empty=keep_empty)

    if format is None:
        filetype = Path(output.name).suffix.lower()
        format = DumpFormat.JSON if filetype == ".json" else DumpFormat.YAML

    match format:
        case DumpFormat.YAML:
            yaml.safe_dump(order_raw, output, allow_unicode=True, sort_keys=False)
        case DumpFormat.JSON:
            json.dump(order_raw, output, indent=2, ensure_ascii=False, sort_keys=False, default=str)
            _ = output.write("\n")
        case _:
            msg = f"unknown filetype target: {format!s}"
            raise click.ClickException(msg)


__all__ = [
    "DumpFormat",
    "dump_order",
]
